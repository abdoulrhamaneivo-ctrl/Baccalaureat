'use strict';

const fs = require('node:fs');
const path = require('node:path');
const countries = require('world-countries');

const root = path.join(__dirname, '..');
const destination = path.join(root, 'dist');
const flagDirectory = path.join(destination, 'flags');

const CAPITALS_FR = {
  AE: ['Abou Dabi'],
  BE: ['Bruxelles'],
  BJ: ['Porto-Novo', 'Cotonou'],
  BO: ['Sucre', 'La Paz'],
  BR: ['Brasília'],
  CH: ['Berne'],
  CI: ['Yamoussoukro', 'Abidjan'],
  CN: ['Pékin'],
  CZ: ['Prague'],
  DK: ['Copenhague'],
  EG: ['Le Caire'],
  GB: ['Londres'],
  GR: ['Athènes'],
  IL: ['Jérusalem'],
  IR: ['Téhéran'],
  KR: ['Séoul'],
  LK: ['Sri Jayawardenepura Kotte', 'Colombo'],
  MM: ['Naypyidaw'],
  NL: ['Amsterdam', 'La Haye'],
  PT: ['Lisbonne'],
  RU: ['Moscou'],
  SE: ['Stockholm'],
  US: ['Washington'],
  VA: ['Vatican'],
  ZA: ['Pretoria', 'Le Cap', 'Bloemfontein'],
};

const CONTINENT_FR = {
  Africa: 'Afrique',
  Americas: 'Amériques',
  Asia: 'Asie',
  Europe: 'Europe',
  Oceania: 'Océanie',
};

function unique(items) {
  return [...new Set(items.filter((item) => typeof item === 'string' && item.trim()).map((item) => item.trim()))];
}

function countryRecord(country) {
  const frenchNames = country.translations?.fra || {};
  const names = unique([
    frenchNames.common,
    country.name.common,
    frenchNames.official,
    country.name.official,
    ...(country.altSpellings || []).filter((name) => name.length > 2 && !/^[A-Z]{2,3}$/.test(name)),
  ]);
  const capitals = CAPITALS_FR[country.cca2] || country.capital || [];
  return {
    code: country.cca2.toLowerCase(),
    alpha2: country.cca2,
    name: frenchNames.common || country.name.common,
    continent: CONTINENT_FR[country.region] || 'Autre',
    names,
    capital: capitals[0] || country.capital?.[0] || '',
    capitals: unique([...(country.capital || []), ...capitals]),
  };
}

const selected = countries
  .filter((country) => (country.unMember || ['PS', 'VA'].includes(country.cca2)) && country.cca2 && country.capital?.length)
  .map(countryRecord)
  .sort((a, b) => a.name.localeCompare(b.name, 'fr'));

if (selected.length < 190) throw new Error(`Expected a global sovereign-state dataset; found only ${selected.length} countries.`);

fs.mkdirSync(flagDirectory, { recursive: true });
for (const entry of fs.readdirSync(flagDirectory)) fs.rmSync(path.join(flagDirectory, entry), { force: true });
for (const country of selected) {
  const source = path.join(root, 'node_modules', 'flag-icons', 'flags', '4x3', `${country.code}.svg`);
  if (!fs.existsSync(source)) throw new Error(`Missing flag asset for ${country.alpha2}.`);
  fs.copyFileSync(source, path.join(flagDirectory, `${country.code}.svg`));
}

const generated = `/* Generated by npm run build:world-data from world-countries and flag-icons. */\n` +
  `const WORLD_COUNTRIES = ${JSON.stringify(selected)};\n` +
  `if (typeof module !== 'undefined' && module.exports) module.exports = WORLD_COUNTRIES;\n` +
  `if (typeof window !== 'undefined') window.WORLD_COUNTRIES = WORLD_COUNTRIES;\n`;
fs.writeFileSync(path.join(destination, 'world-data.js'), generated);
fs.copyFileSync(path.join(root, 'node_modules', 'flag-icons', 'LICENSE'), path.join(flagDirectory, 'LICENSE.txt'));
fs.copyFileSync(path.join(root, 'node_modules', 'world-countries', 'LICENSE'), path.join(destination, 'world-data-ODbL-LICENSE.txt'));
fs.writeFileSync(path.join(destination, 'world-data-ATTRIBUTION.txt'),
  'Country names and capital data: mledoze/countries, distributed under the Open Database License (ODbL-1.0).\n' +
  'https://github.com/mledoze/countries\n\n' +
  'Flag SVG artwork: lipis/flag-icons, distributed under the MIT License; see flags/LICENSE.txt.\n' +
  'https://github.com/lipis/flag-icons\n');

console.log(`Generated ${selected.length} country records and local flag SVGs.`);
